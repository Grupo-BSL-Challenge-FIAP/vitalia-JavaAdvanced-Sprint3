DECLARE
V_CAO_ID       NUMBER;
    V_CACHORRO_ID  NUMBER;
BEGIN
BEGIN
SELECT SPECIES_ID
INTO V_CAO_ID
FROM TB_VITALIA_SPECIES
WHERE UPPER(NAME) = 'CÃO';

EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_CAO_ID := NULL;
END;

BEGIN
SELECT SPECIES_ID
INTO V_CACHORRO_ID
FROM TB_VITALIA_SPECIES
WHERE UPPER(NAME) = 'CACHORRO';

EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_CACHORRO_ID := NULL;
END;

    IF V_CACHORRO_ID IS NOT NULL THEN

        IF V_CAO_ID IS NULL THEN

UPDATE TB_VITALIA_SPECIES
SET NAME = 'Cão'
WHERE SPECIES_ID = V_CACHORRO_ID;

ELSE

UPDATE TB_VITALIA_BREED
SET SPECIES_ID = V_CAO_ID
WHERE SPECIES_ID = V_CACHORRO_ID;

DELETE FROM TB_VITALIA_SPECIES
WHERE SPECIES_ID = V_CACHORRO_ID;

END IF;

END IF;
END;
