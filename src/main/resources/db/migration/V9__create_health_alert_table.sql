DECLARE
v_count NUMBER;
BEGIN
SELECT COUNT(*) INTO v_count
FROM user_tables
WHERE table_name = 'TB_VITALIA_HEALTH_ALERT';

IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE tb_vitalia_health_alert (
                alert_id       NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                pet_id         NUMBER(19,0) NOT NULL,
                measurement_id NUMBER(19,0),
                alert_type     VARCHAR2(200 CHAR) NOT NULL,
                message        VARCHAR2(4000 CHAR) NOT NULL,
                severity       VARCHAR2(80 CHAR) NOT NULL,
                status         VARCHAR2(80 CHAR) NOT NULL,
                created_at     TIMESTAMP(6) NOT NULL,
                resolved_at    TIMESTAMP(6),
                PRIMARY KEY (alert_id)
            )';

EXECUTE IMMEDIATE '
ALTER TABLE tb_vitalia_health_alert
    ADD CONSTRAINT fk_vitalia_alert_pet
        FOREIGN KEY (pet_id) REFERENCES tb_vitalia_pet (pet_id)';

EXECUTE IMMEDIATE '
ALTER TABLE tb_vitalia_health_alert
    ADD CONSTRAINT fk_vitalia_alert_measurement
        FOREIGN KEY (measurement_id) REFERENCES tb_vitalia_health_measurement (measurement_id)';
END IF;
END;
/